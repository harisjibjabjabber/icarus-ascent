"""Bake the MiniPoly "Witch Broom" (CC0, poly.pizza/m/gwE8397gO3) into src/render/broomMesh.ts.
Retexture = palette-atlas remap (minipoly-witch-broom-palette-retex.png) sampled per vertex into vertex colours,
so the game needs no texture and node tests can build it. Output is already in the broom frame:
+X nose, bristles toward -X, handle centre line on y = 0 (feet plant on top), split into handle / straw parts."""
import json, struct, sys
import numpy as np
from PIL import Image
SRC = 'spikes/town-proof/assets/broom/minipoly-witch-broom.glb'
PAL = 'spikes/town-proof/assets/broom/minipoly-witch-broom-palette-retex.png'
LENGTH, CROSS = 2.8, 0.6  # m along the broom, cross-section squash (the source straw bulb is fat)
b = open(SRC, 'rb').read(); l = struct.unpack('<I', b[12:16])[0]; j = json.loads(b[20:20 + l])
off = 20 + l; bl = struct.unpack('<I', b[off:off + 4])[0]; binb = b[off + 8:off + 8 + bl]
def acc(i, dt=np.float32):
    a = j['accessors'][i]; bv = j['bufferViews'][a['bufferView']]; n = {'VEC2': 2, 'VEC3': 3, 'SCALAR': 1}[a['type']]
    dt = {5126: np.float32, 5123: np.uint16, 5125: np.uint32}[a['componentType']]
    o = bv.get('byteOffset', 0) + a.get('byteOffset', 0)
    return np.frombuffer(binb, dtype=dt, count=a['count'] * n, offset=o).reshape(-1, n) if n > 1 else np.frombuffer(binb, dtype=dt, count=a['count'], offset=o)
p = j['meshes'][0]['primitives'][0]
pos = acc(p['attributes']['POSITION']).astype(np.float64); nor = acc(p['attributes']['NORMAL']).astype(np.float64)
uv = acc(p['attributes']['TEXCOORD_0']); idx = acc(p['indices']).astype(np.int64).reshape(-1, 3)
# orient: source long axis d (bristles at origin, handle toward +x+z) -> +X
d = np.array([0.0122, 0, 0.0132]); d /= np.linalg.norm(d)
ex = d; ey = np.array([0, 1.0, 0]); ez = np.cross(ex, ey)
R = np.stack([ex, ey, ez])  # rows: new axes in old coords
P = pos @ R.T; N = nor @ R.T
pal = np.array(Image.open(PAL).convert('RGB')).astype(np.float64) / 255
px = np.clip((uv[:, 0] * 512).astype(int), 0, 511); py = np.clip((uv[:, 1] * 512).astype(int), 0, 511)
col = pal[py, px]
straw = (px >= 256) & (px < 288)
# piecewise stretch along the broom: visible handle (binding -> nose) = HANDLE m, straw (tail -> binding) = STRAW m;
# cross-sections scaled separately (handle ~ RADIUS thick under her feet, straw bulb ~ STRAW_W across)
HANDLE, STRAW, H_CROSS, S_CROSS = 2.0, 0.82, 1.0, 1.0
bind = P[straw, 0].max(); x0 = P[:, 0].min(); x1 = P[:, 0].max()
kH = HANDLE / (x1 - bind); kS = STRAW / (bind - x0)
isS = P[:, 0] <= bind
xs = np.where(isS, (P[:, 0] - bind) * kS, (P[:, 0] - bind) * kH) - 0.72
# cross scale: handle verts by kH*H_CROSS*hc, straw by kS*S_CROSS (set below from targets)
hmid = (~straw) & (P[:, 0] > bind + 0.3 * (x1 - bind)) & (P[:, 0] < bind + 0.7 * (x1 - bind))
cy, cz = np.median(P[hmid, 1]), np.median(P[hmid, 2])
hr = np.percentile(np.hypot(P[hmid, 1] - cy, P[hmid, 2] - cz), 90)
sw = (P[straw, 2].max() - P[straw, 2].min()) / 2
hs = 0.115 / hr; ss = 0.21 / sw  # handle radius 3.4 cm, straw bulb half-width 21 cm
sc = np.where(straw, ss, hs)
# blend the scale smoothly over the binding so the cord does not tear
P = np.stack([xs, (P[:, 1] - cy) * sc, (P[:, 2] - cz) * sc], 1)
sy = P[straw, 1]; P[straw, 1] = (sy - (sy.max() + sy.min()) / 2) * 0.75 + 0.01  # straw bulb centred on the handle, a bit flatter
feet = (~straw) & (np.abs(P[:, 0]) < 0.3)
P[:, 1] -= (P[feet, 1].max() + P[feet, 1].min()) / 2 + 0.01  # handle centre under the feet at y = -0.01 (as the old broom)
P[:, 2] -= (P[feet, 2].max() + P[feet, 2].min()) / 2
N = N / np.stack([np.where(isS, kS, kH), sc, sc], 1); N /= np.linalg.norm(N, axis=1, keepdims=True)
tri_straw = straw[idx].all(axis=1)
def part(mask):
    t = idx[mask]; used = np.unique(t); remap = -np.ones(len(P), int); remap[used] = np.arange(len(used))
    return P[used], N[used], col[used], remap[t]
out = {}
for name, m in (('handle', ~tri_straw), ('straw', tri_straw)):
    pp, nn, cc, tt = part(m)
    out[name] = dict(p=[round(float(v), 4) for v in pp.ravel()], n=[round(float(v), 3) for v in nn.ravel()],
                     c=[int(v * 255 + 0.5) for v in cc.ravel()], i=[int(v) for v in tt.ravel()])
    print(name, len(pp), 'verts', len(tt), 'tris', 'x', pp[:, 0].min().round(3), pp[:, 0].max().round(3), 'y', pp[:, 1].min().round(3), pp[:, 1].max().round(3), 'z', pp[:, 2].min().round(3), pp[:, 2].max().round(3))
hp = np.array(out['handle']['p']).reshape(-1, 3)
for x in (-0.23, 0.0, 0.23, 0.6):
    sel = np.abs(hp[:, 0] - x) < 0.05
    if sel.any(): print('handle @x', x, 'top y', hp[sel, 1].max().round(3), 'bottom', hp[sel, 1].min().round(3))
with open('src/render/broomMesh.ts', 'w') as f:
    f.write('// GENERATED by art/pipeline/bake_broom.py from the MiniPoly "Witch Broom" (CC0, https://poly.pizza/m/gwE8397gO3),\n')
    f.write('// palette-retextured to our colours (vertex colours, no texture). Do not edit by hand.\n')
    f.write('export interface BakedPart { p: number[]; n: number[]; c: number[]; i: number[] }\n')
    for k, v in out.items(): f.write(f'export const BROOM_{k.upper()}: BakedPart = {json.dumps(v, separators=(",", ":"))};\n')
